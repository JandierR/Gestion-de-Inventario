public class Ubicacion {
    private String nombreLugar;

    public Ubicacion(String nombreLugar) {
        this.nombreLugar = nombreLugar;
    }

    public String getNombreLugar() {
        return nombreLugar;
    }

    public void setNombreLugar(String nombreLugar) {
        this.nombreLugar = nombreLugar;
    }
}
